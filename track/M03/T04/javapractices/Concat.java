
class Concat {

    public static void main(String[] args) {
        String s1 = "varshini";
        String s2 = "deepthi";
        String s3 = s1 + s2;
        System.out.println(s3);
        String t1 = new String("Anu");
        String t2 = new String("bany");
        String res = t1.concat(t2);
        System.out.println(res);
    }
}
